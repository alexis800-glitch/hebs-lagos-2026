/**
 * Media prepared for publication (lib/assets/published-media-2027.ts).
 * `npm run media:prepare` copies the approved files into public/2027/media/ and
 * records their hashes; otherwise this test checks the record against the register
 * and, where the files are present, against the files.
 */
import { describe, expect, it } from "vitest";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REVIEW_ASSETS } from "../lib/assets/home-2027-review";
import { MEDIA_RELEASED, PUBLISHED_MEDIA, assetFiles } from "../lib/assets/published-media-2027";

const ROOT = join(__dirname, "..");
const REVIEW = join(ROOT, "public/_review/home-2027");
const MEDIA = join(ROOT, "public/2027/media");
const MANIFEST = join(ROOT, "lib/assets/published-media-2027.json");
const sha = (f: string) => createHash("sha256").update(readFileSync(f)).digest("hex");

const expected = Array.from(new Set(REVIEW_ASSETS.filter((a) => a.published).flatMap(assetFiles))).sort();

describe("published media", () => {
  if (process.env.UPDATE_PUBLISHED_MEDIA === "1") {
    mkdirSync(MEDIA, { recursive: true });
    const files: Record<string, string> = {};
    for (const f of expected) {
      copyFileSync(join(REVIEW, f), join(MEDIA, f));
      files[f] = sha(join(MEDIA, f));
    }
    writeFileSync(MANIFEST, JSON.stringify({ note: "Generated by npm run media:prepare. Do not edit by hand.", files }, null, 1) + "\n");
  }
  const recorded = JSON.parse(readFileSync(MANIFEST, "utf8")).files as Record<string, string>;

  it("records every file of every approved asset, and nothing else", () => {
    expect(Object.keys(recorded).sort()).toEqual(expected);
    expect(Object.keys(PUBLISHED_MEDIA).length).toBe(expected.length);
  });

  it("never includes restricted media", () => {
    const restricted = new Set(REVIEW_ASSETS.filter((a) => a.restricted).flatMap(assetFiles));
    for (const f of expected) expect(restricted.has(f), f).toBe(false);
    for (const f of expected) expect(f.startsWith("x-"), f).toBe(false);
  });

  it("matches the prepared files, where they are present", () => {
    if (!existsSync(MEDIA)) return;
    for (const f of expected) {
      expect(existsSync(join(MEDIA, f)), f).toBe(true);
      expect(sha(join(MEDIA, f)), f).toBe(recorded[f]);
    }
  });

  it("keeps the files out of the public repository until the launch commit", () => {
    const tracked = execFileSync("git", ["ls-files", "public/2027/media"], { cwd: ROOT, encoding: "utf8" }).trim();
    if (MEDIA_RELEASED) expect(tracked.split("\n").sort()).toEqual(expected.map((f) => `public/2027/media/${f}`));
    else {
      expect(tracked).toBe("");
      expect(readFileSync(join(ROOT, ".gitignore"), "utf8")).toMatch(/^\/?public\/2027\/media\/?$/m);
    }
  });
});
